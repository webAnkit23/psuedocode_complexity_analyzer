"""
run_all_examples.py - analyze every file in examples/ and write ANALYSIS_REPORT.md

    python run_all_examples.py
"""
import os
import sys

from Parser import Parser
from program_analyzer import ProgramAnalyzer

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    out = ["# Analysis report (generated by run_all_examples.py)\n",
           "Worst-case estimates. V = vertices, E = edges, n = input size, "
           "deg = degree of the current vertex.\n"]
    summary = []
    folder = os.path.join(HERE, "examples")
    for name in sorted(os.listdir(folder)):
        if not name.endswith(".txt"):
            continue
        code = open(os.path.join(folder, name), encoding="utf-8").read()
        out += [f"\n## {name}\n", "```text", code.rstrip(), "```\n"]
        try:
            results = ProgramAnalyzer(Parser(code).parse()).analyze()
        except SyntaxError as error:
            out.append(f"**Syntax error:** {error}\n")
            continue
        out.append("| Function | Time complexity |\n|---|---|")
        for r in results:
            out.append(f"| `{r.name}` | `{r.text}` |")
            summary.append((name, r.name, r.text))
        for r in results:
            extra = []
            if r.recurrence is not None:
                extra += [f"- recurrence: `{line}`" for line in r.recurrence.describe()]
            extra += [f"- note: {n}" for n in r.notes]
            extra += [f"- warning: {w}" for w in r.warnings]
            if extra:
                out += [f"\n`{r.name}`:"] + extra
        out.append("")
    path = os.path.join(HERE, "ANALYSIS_REPORT.md")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(out))
    print(f"wrote {path}  ({len(summary)} functions analysed)")


if __name__ == "__main__":
    sys.exit(main())
